//! Node modules integrity scanner — detects corrupted pnpm `node_modules/`
//! structures (e.g. when `npm install` or `yarn install` is accidentally run in
//! a pnpm workspace, replacing symlinks with real copies).

use crate::scanners::ScannerIssue;
use crate::utils::Result;
use std::path::Path;

pub struct NodeModulesIntegrityScanner {
    check_symlink_structure: bool,
    check_modules_yaml: bool,
    check_no_foreign_lockfiles: bool,
    require_package_manager_field: bool,
}

impl NodeModulesIntegrityScanner {
    pub fn new() -> Self {
        Self {
            check_symlink_structure: true,
            check_modules_yaml: true,
            check_no_foreign_lockfiles: true,
            require_package_manager_field: true,
        }
    }

    pub fn with_config(
        check_symlink_structure: bool,
        check_modules_yaml: bool,
        check_no_foreign_lockfiles: bool,
        require_package_manager_field: bool,
    ) -> Self {
        Self {
            check_symlink_structure,
            check_modules_yaml,
            check_no_foreign_lockfiles,
            require_package_manager_field,
        }
    }

    /// Scan a project root for `node_modules/` integrity issues.
    /// Only activates when `pnpm-lock.yaml` exists (pnpm workspace).
    /// Silent when `node_modules/` doesn't exist (not installed).
    pub fn scan(&self, project_path: &str) -> Result<Vec<ScannerIssue>> {
        let root = Path::new(project_path);
        let mut issues = Vec::new();

        if !root.join("pnpm-lock.yaml").exists() {
            return Ok(issues);
        }

        let node_modules = root.join("node_modules");
        if !node_modules.exists() {
            return Ok(issues);
        }

        if self.check_symlink_structure {
            issues.extend(self.check_pnpm_structure(&node_modules));
        }

        if self.check_modules_yaml {
            issues.extend(self.check_modules_yaml_file(&node_modules));
        }

        if self.check_no_foreign_lockfiles {
            issues.extend(self.check_foreign_lockfiles(&node_modules));
        }

        if self.require_package_manager_field {
            issues.extend(self.check_package_manager_field(root));
        }

        Ok(issues)
    }

    fn check_pnpm_structure(&self, node_modules: &Path) -> Vec<ScannerIssue> {
        let mut issues = Vec::new();

        let pnpm_dir = node_modules.join(".pnpm");
        if !pnpm_dir.exists() {
            issues.push(ScannerIssue::new(
                "node-modules-pnpm-structure",
                "error",
                "node_modules",
                "pnpm-lock.yaml present but node_modules/.pnpm/ is missing; \
                 someone may have run npm/yarn install instead of pnpm install",
            ));
            return issues;
        }

        if let Ok(entries) = std::fs::read_dir(node_modules) {
            for entry in entries.filter_map(|e| e.ok()) {
                let name = entry.file_name();
                let name_str = name.to_string_lossy();
                if name_str.starts_with('.') {
                    continue;
                }
                let path = entry.path();
                let meta = std::fs::symlink_metadata(&path);
                match meta {
                    Ok(m) if !m.is_symlink() && m.is_dir() => {
                        issues.push(ScannerIssue::new(
                            "node-modules-symlinks-valid",
                            "error",
                            "node_modules",
                            format!(
                                "node_modules/{} is a real directory, not a symlink; \
                                 pnpm structure may be corrupted",
                                name_str
                            ),
                        ));
                    }
                    _ => {}
                }
            }
        }

        issues
    }

    fn check_modules_yaml_file(&self, node_modules: &Path) -> Vec<ScannerIssue> {
        let mut issues = Vec::new();

        let modules_yaml = node_modules.join(".modules.yaml");
        if !modules_yaml.exists() {
            issues.push(ScannerIssue::new(
                "node-modules-modules-yaml",
                "error",
                "node_modules",
                "node_modules/.modules.yaml is missing; cannot verify package manager",
            ));
            return issues;
        }

        if let Ok(content) = std::fs::read_to_string(&modules_yaml) {
            let is_pnpm = content
                .lines()
                .any(|l| l.trim().starts_with("packageManager:") && l.contains("pnpm"));
            if !is_pnpm {
                let pm = content
                    .lines()
                    .find(|l| l.trim().starts_with("packageManager:"))
                    .unwrap_or("unknown")
                    .trim();
                issues.push(ScannerIssue::new(
                    "node-modules-modules-yaml",
                    "error",
                    "node_modules/.modules.yaml",
                    format!(
                        "node_modules/.modules.yaml packageManager is not pnpm (found: {})",
                        pm
                    ),
                ));
            }
        }

        issues
    }

    fn check_foreign_lockfiles(&self, node_modules: &Path) -> Vec<ScannerIssue> {
        let mut issues = Vec::new();

        for lockfile in &["package-lock.json", "yarn.lock"] {
            if node_modules.join(lockfile).exists() {
                issues.push(ScannerIssue::new(
                    "node-modules-no-npm-lock",
                    "error",
                    &format!("node_modules/{}", lockfile),
                    format!(
                        "node_modules/ contains {} alongside pnpm-lock.yaml; \
                         wrong package manager was run",
                        lockfile
                    ),
                ));
            }
        }

        issues
    }

    fn check_package_manager_field(&self, root: &Path) -> Vec<ScannerIssue> {
        let mut issues = Vec::new();

        let pkg_json = root.join("package.json");
        if !pkg_json.exists() {
            return issues;
        }

        let content = match std::fs::read_to_string(&pkg_json) {
            Ok(c) => c,
            Err(_) => return issues,
        };

        let parsed: serde_json::Value = match serde_json::from_str(&content) {
            Ok(v) => v,
            Err(_) => return issues,
        };

        let pm = parsed.get("packageManager").and_then(|v| v.as_str());
        match pm {
            Some(pm_str) if pm_str.starts_with("pnpm") => {}
            Some(other) => {
                issues.push(ScannerIssue::new(
                    "node-modules-package-manager-field",
                    "warning",
                    "package.json",
                    format!(
                        "package.json 'packageManager' is '{}' but pnpm-lock.yaml is present; \
                         should be 'pnpm@<version>'",
                        other
                    ),
                ));
            }
            None => {
                issues.push(ScannerIssue::new(
                    "node-modules-package-manager-field",
                    "warning",
                    "package.json",
                    "package.json missing 'packageManager' field; \
                     should be set to 'pnpm@<version>' in pnpm workspaces",
                ));
            }
        }

        issues
    }
}

impl Default for NodeModulesIntegrityScanner {
    fn default() -> Self {
        Self::new()
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use tempfile::TempDir;

    #[test]
    fn silent_without_pnpm_lock() -> Result<()> {
        let dir = TempDir::new()?;
        std::fs::create_dir_all(dir.path().join("node_modules"))?;
        let scanner = NodeModulesIntegrityScanner::new();
        assert!(scanner.scan(&dir.path().to_string_lossy())?.is_empty());
        Ok(())
    }

    #[test]
    fn silent_without_node_modules() -> Result<()> {
        let dir = TempDir::new()?;
        std::fs::write(dir.path().join("pnpm-lock.yaml"), "")?;
        let scanner = NodeModulesIntegrityScanner::new();
        assert!(scanner.scan(&dir.path().to_string_lossy())?.is_empty());
        Ok(())
    }

    #[test]
    fn flags_missing_pnpm_dir() -> Result<()> {
        let dir = TempDir::new()?;
        std::fs::write(dir.path().join("pnpm-lock.yaml"), "")?;
        std::fs::create_dir_all(dir.path().join("node_modules").join("some-pkg"))?;
        let scanner = NodeModulesIntegrityScanner::new();
        let issues = scanner.scan(&dir.path().to_string_lossy())?;
        assert!(issues
            .iter()
            .any(|i| i.rule == "node-modules-pnpm-structure" && i.severity == "error"));
        Ok(())
    }

    #[test]
    fn flags_real_dir_instead_of_symlink() -> Result<()> {
        let dir = TempDir::new()?;
        std::fs::write(dir.path().join("pnpm-lock.yaml"), "")?;
        let nm = dir.path().join("node_modules");
        std::fs::create_dir_all(nm.join(".pnpm"))?;
        std::fs::create_dir_all(nm.join("some-pkg"))?;
        let scanner = NodeModulesIntegrityScanner::new();
        let issues = scanner.scan(&dir.path().to_string_lossy())?;
        assert!(issues
            .iter()
            .any(|i| i.rule == "node-modules-symlinks-valid"));
        Ok(())
    }

    #[test]
    fn symlinked_packages_no_symlink_issue() -> Result<()> {
        let dir = TempDir::new()?;
        std::fs::write(dir.path().join("pnpm-lock.yaml"), "")?;
        let nm = dir.path().join("node_modules");
        std::fs::create_dir_all(nm.join(".pnpm"))?;
        let target = nm.join(".pnpm").join("some-pkg");
        std::fs::create_dir_all(&target)?;
        std::os::unix::fs::symlink(&target, nm.join("some-pkg"))?;
        let scanner = NodeModulesIntegrityScanner::new();
        let issues = scanner.scan(&dir.path().to_string_lossy())?;
        assert!(!issues
            .iter()
            .any(|i| i.rule == "node-modules-symlinks-valid"));
        Ok(())
    }

    #[test]
    fn flags_missing_modules_yaml() -> Result<()> {
        let dir = TempDir::new()?;
        std::fs::write(dir.path().join("pnpm-lock.yaml"), "")?;
        let nm = dir.path().join("node_modules");
        std::fs::create_dir_all(nm.join(".pnpm"))?;
        let scanner = NodeModulesIntegrityScanner::new();
        let issues = scanner.scan(&dir.path().to_string_lossy())?;
        assert!(issues.iter().any(|i| i.rule == "node-modules-modules-yaml"));
        Ok(())
    }

    #[test]
    fn flags_non_pnpm_modules_yaml() -> Result<()> {
        let dir = TempDir::new()?;
        std::fs::write(dir.path().join("pnpm-lock.yaml"), "")?;
        let nm = dir.path().join("node_modules");
        std::fs::create_dir_all(nm.join(".pnpm"))?;
        std::fs::write(nm.join(".modules.yaml"), "packageManager: npm\n")?;
        let scanner = NodeModulesIntegrityScanner::new();
        let issues = scanner.scan(&dir.path().to_string_lossy())?;
        assert!(issues
            .iter()
            .any(|i| i.rule == "node-modules-modules-yaml" && i.message.contains("npm")));
        Ok(())
    }

    #[test]
    fn pnpm_modules_yaml_no_issue() -> Result<()> {
        let dir = TempDir::new()?;
        std::fs::write(dir.path().join("pnpm-lock.yaml"), "")?;
        let nm = dir.path().join("node_modules");
        std::fs::create_dir_all(nm.join(".pnpm"))?;
        std::os::unix::fs::symlink(nm.join(".pnpm"), nm.join("some-pkg-link")).ok();
        std::fs::write(nm.join(".modules.yaml"), "packageManager: pnpm@9.0.0\n")?;
        let scanner = NodeModulesIntegrityScanner::new();
        let issues = scanner.scan(&dir.path().to_string_lossy())?;
        assert!(!issues.iter().any(|i| i.rule == "node-modules-modules-yaml"));
        Ok(())
    }

    #[test]
    fn flags_foreign_lockfile_in_node_modules() -> Result<()> {
        let dir = TempDir::new()?;
        std::fs::write(dir.path().join("pnpm-lock.yaml"), "")?;
        let nm = dir.path().join("node_modules");
        std::fs::create_dir_all(nm.join(".pnpm"))?;
        std::fs::write(nm.join("package-lock.json"), "")?;
        let scanner = NodeModulesIntegrityScanner::new();
        let issues = scanner.scan(&dir.path().to_string_lossy())?;
        assert!(issues.iter().any(|i| i.rule == "node-modules-no-npm-lock"));
        Ok(())
    }

    #[test]
    fn flags_missing_package_manager_field() -> Result<()> {
        let dir = TempDir::new()?;
        std::fs::write(dir.path().join("pnpm-lock.yaml"), "")?;
        std::fs::write(dir.path().join("package.json"), r#"{"name": "test"}"#)?;
        let nm = dir.path().join("node_modules");
        std::fs::create_dir_all(nm.join(".pnpm"))?;
        std::fs::write(nm.join(".modules.yaml"), "packageManager: pnpm@9.0.0\n")?;
        let scanner = NodeModulesIntegrityScanner::new();
        let issues = scanner.scan(&dir.path().to_string_lossy())?;
        assert!(issues
            .iter()
            .any(|i| i.rule == "node-modules-package-manager-field"));
        Ok(())
    }

    #[test]
    fn flags_wrong_package_manager_field() -> Result<()> {
        let dir = TempDir::new()?;
        std::fs::write(dir.path().join("pnpm-lock.yaml"), "")?;
        std::fs::write(
            dir.path().join("package.json"),
            r#"{"name": "test", "packageManager": "npm@10.0.0"}"#,
        )?;
        let nm = dir.path().join("node_modules");
        std::fs::create_dir_all(nm.join(".pnpm"))?;
        std::fs::write(nm.join(".modules.yaml"), "packageManager: pnpm@9.0.0\n")?;
        let scanner = NodeModulesIntegrityScanner::new();
        let issues = scanner.scan(&dir.path().to_string_lossy())?;
        assert!(issues
            .iter()
            .any(|i| i.rule == "node-modules-package-manager-field" && i.message.contains("npm")));
        Ok(())
    }

    #[test]
    fn correct_package_manager_field_no_issue() -> Result<()> {
        let dir = TempDir::new()?;
        std::fs::write(dir.path().join("pnpm-lock.yaml"), "")?;
        std::fs::write(
            dir.path().join("package.json"),
            r#"{"name": "test", "packageManager": "pnpm@9.0.0"}"#,
        )?;
        let nm = dir.path().join("node_modules");
        std::fs::create_dir_all(nm.join(".pnpm"))?;
        std::fs::write(nm.join(".modules.yaml"), "packageManager: pnpm@9.0.0\n")?;
        let scanner = NodeModulesIntegrityScanner::new();
        let issues = scanner.scan(&dir.path().to_string_lossy())?;
        assert!(!issues
            .iter()
            .any(|i| i.rule == "node-modules-package-manager-field"));
        Ok(())
    }

    #[test]
    fn config_can_disable_all_checks() -> Result<()> {
        let dir = TempDir::new()?;
        std::fs::write(dir.path().join("pnpm-lock.yaml"), "")?;
        let nm = dir.path().join("node_modules");
        std::fs::create_dir_all(nm.join("some-pkg"))?;
        std::fs::write(nm.join("package-lock.json"), "")?;
        let scanner = NodeModulesIntegrityScanner::with_config(false, false, false, false);
        assert!(scanner.scan(&dir.path().to_string_lossy())?.is_empty());
        Ok(())
    }
}
