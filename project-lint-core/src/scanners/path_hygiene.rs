//! Path hygiene scanner — validates all committed text files for path
//! hygiene: no absolute home paths, no AI attribution boilerplate, no AI
//! signature comments in source headers. Enforces three rules:
//!
//! 1. **no-absolute-home-paths** — no committed file should contain
//!    `/Users/<username>/` or `/home/<username>/` paths (warning).
//!    Exempt files (`.envrc`, `.gitignore`, `*.env`) that legitimately
//!    reference home paths are skipped.
//! 2. **no-ai-attribution** — no committed file should contain AI tool
//!    attribution boilerplate like "Generated with [Devin]" or
//!    "Co-Authored-By: Devin" (error).
//! 3. **no-ai-signature-comments** — no committed file should contain
//!    AI tool signature comments in source code headers (error).
//!
//! This scanner is cross-cutting (all text files) and uses the
//! centralized exclusion list to skip `node_modules/`, `target/`, etc.

use crate::scanners::ScannerIssue;
