    fn skips_excluded_dirs() -> Result<()> {
        let dir = TempDir::new()?;
        std::fs::create_dir_all(dir.path().join("target"))?;
        std::fs::write(
            dir.path().join("target").join("build.rs"),
            "// AI-generated\nfn main() {}\n",
        )?;
        let scanner = PathHygieneScanner::new();
        let issues = scanner.scan(&dir.path().to_string_lossy())?;
        assert!(!issues
            .iter()
            .any(|i| i.rule == "no-ai-signature-comments" && i.file.contains("target/")));
        Ok(())
    }

    #[test]
    fn custom_attribution_patterns() -> Result<()> {
        let dir = TempDir::new()?;
        std::fs::write(dir.path().join("README.md"), "# Project\n\nMade by BotX\n")?;
        let scanner = PathHygieneScanner::with_config(
            true,
            true,
            true,
            Vec::new(),
            vec!["Made by BotX".to_string()],
            Vec::new(),
        );
        let issues = scanner.scan(&dir.path().to_string_lossy())?;
        assert!(issues
            .iter()
            .any(|i| i.rule == "no-ai-attribution" && i.message.contains("BotX")));
        Ok(())
    }

    #[test]
    fn has_absolute_home_path_detects() {
        assert!(has_absolute_home_path("let p = \"/Users/micro/code\";"));
        assert!(has_absolute_home_path("path = \"/home/dev/code\""));
        assert!(!has_absolute_home_path("let p = \"./relative/path\";"));
    }

    #[test]
    fn is_text_file_detects_extensions() {
        let scanner = PathHygieneScanner::new();
        assert!(scanner.is_text_file(Path::new("main.rs")));
        assert!(scanner.is_text_file(Path::new("config.yaml")));
        assert!(scanner.is_text_file(Path::new("Dockerfile")));
        assert!(!scanner.is_text_file(Path::new("image.png")));
        assert!(!scanner.is_text_file(Path::new("binary")));
    }
