/// Default exempt file patterns for the `no-absolute-home-paths` rule.
pub const DEFAULT_EXEMPT_FILES: &[&str] = &[".envrc", ".gitignore", "*.env", "*.env.*"];

/// Default AI-attribution patterns for the `no-ai-attribution` rule.
pub const DEFAULT_AI_ATTRIBUTION_PATTERNS: &[&str] = &[
    "Generated with [Devin]",
    "Co-Authored-By: Devin",
    "Generated by AI",
    "Generated by Devin",
];

/// Default AI-signature comment patterns for the `no-ai-signature-comments`
